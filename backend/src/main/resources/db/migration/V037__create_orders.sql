-- A customer order. Four independent status dimensions; money and addresses are frozen snapshots.
CREATE TABLE orders (
    id                BIGINT        NOT NULL AUTO_INCREMENT,
    public_id         VARCHAR(36)   NOT NULL,
    order_number      VARCHAR(30)   NOT NULL,
    user_id           BIGINT        NOT NULL,
    order_type        VARCHAR(20)   NOT NULL DEFAULT 'NORMAL',
    order_status      VARCHAR(20)   NOT NULL DEFAULT 'PENDING_PAYMENT',
    payment_status    VARCHAR(20)   NOT NULL DEFAULT 'PENDING',
    production_status VARCHAR(20)   NOT NULL DEFAULT 'NOT_REQUIRED',
    shipment_status   VARCHAR(20)   NOT NULL DEFAULT 'NOT_SHIPPED',
    payment_method    VARCHAR(10)   NOT NULL DEFAULT 'ONLINE',
    customer_name     VARCHAR(120)  NOT NULL,
    customer_email    VARCHAR(254)  NOT NULL,
    customer_phone    VARCHAR(20)   NULL,
    ship_name         VARCHAR(120)  NOT NULL,
    ship_phone        VARCHAR(20)   NOT NULL,
    ship_line1        VARCHAR(200)  NOT NULL,
    ship_line2        VARCHAR(200)  NULL,
    ship_city         VARCHAR(80)   NOT NULL,
    ship_state        VARCHAR(60)   NOT NULL,
    ship_pincode      VARCHAR(6)    NOT NULL,
    bill_name         VARCHAR(120)  NOT NULL,
    bill_phone        VARCHAR(20)   NOT NULL,
    bill_line1        VARCHAR(200)  NOT NULL,
    bill_line2        VARCHAR(200)  NULL,
    bill_city         VARCHAR(80)   NOT NULL,
    bill_state        VARCHAR(60)   NOT NULL,
    bill_pincode      VARCHAR(6)    NOT NULL,
    shipping_zone_code VARCHAR(30)  NULL,
    coupon_code       VARCHAR(40)   NULL,
    subtotal          DECIMAL(12,2) NOT NULL,
    discount_total    DECIMAL(12,2) NOT NULL,
    shipping_total    DECIMAL(12,2) NOT NULL,
    tax_total         DECIMAL(12,2) NOT NULL,
    grand_total       DECIMAL(12,2) NOT NULL,
    amount_paid       DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    idempotency_key   VARCHAR(64)   NOT NULL,
    request_hash      VARCHAR(64)   NOT NULL,
    payment_due_at    DATETIME(6)   NULL,
    placed_at         DATETIME(6)   NOT NULL,
    version           BIGINT        NOT NULL DEFAULT 0,
    created_at        DATETIME(6)   NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at        DATETIME(6)   NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uq_orders_public_id (public_id),
    UNIQUE KEY uq_orders_order_number (order_number),
    UNIQUE KEY uq_orders_user_idempotency (user_id, idempotency_key),
    KEY idx_orders_user_placed (user_id, placed_at),
    KEY idx_orders_status_due (order_status, payment_due_at),
    CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_orders_type CHECK (order_type IN ('NORMAL')),
    CONSTRAINT ck_orders_status CHECK (order_status IN ('PENDING_PAYMENT','CONFIRMED','PROCESSING','COMPLETED','CANCELLED')),
    CONSTRAINT ck_orders_payment_status CHECK (payment_status IN ('PENDING','PAID','FAILED','COD_PENDING','PARTIALLY_REFUNDED','REFUNDED')),
    CONSTRAINT ck_orders_production_status CHECK (production_status IN ('NOT_REQUIRED','PENDING','IN_PRODUCTION','COMPLETED')),
    CONSTRAINT ck_orders_shipment_status CHECK (shipment_status IN ('NOT_SHIPPED','PACKED','SHIPPED','OUT_FOR_DELIVERY','DELIVERED','RETURNED')),
    CONSTRAINT ck_orders_method CHECK (payment_method IN ('ONLINE','COD')),
    CONSTRAINT ck_orders_amounts CHECK (subtotal >= 0 AND discount_total >= 0 AND shipping_total >= 0
        AND tax_total >= 0 AND grand_total >= 0 AND amount_paid >= 0 AND discount_total <= subtotal),
    CONSTRAINT ck_orders_grand_total CHECK (grand_total = subtotal - discount_total + tax_total + shipping_total),
    CONSTRAINT ck_orders_paid_within_total CHECK (amount_paid <= grand_total),
    CONSTRAINT ck_orders_pincodes CHECK (ship_pincode REGEXP '^[1-9][0-9]{5}$' AND bill_pincode REGEXP '^[1-9][0-9]{5}$')
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_0900_ai_ci;
