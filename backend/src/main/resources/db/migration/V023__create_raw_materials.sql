CREATE TABLE raw_materials (
                               id                  BIGINT         NOT NULL AUTO_INCREMENT,
                               public_id           CHAR(36)       NOT NULL,
                               code                VARCHAR(40)    NOT NULL,
                               name                VARCHAR(150)   NOT NULL,
                               category            VARCHAR(20)    NOT NULL,
                               uom                 VARCHAR(20)    NOT NULL,
                               on_hand             DECIMAL(14,3)  NOT NULL DEFAULT 0,
                               reserved            DECIMAL(14,3)  NOT NULL DEFAULT 0,
                               low_stock_threshold DECIMAL(14,3)  NOT NULL DEFAULT 0,
                               unit_cost           DECIMAL(12,4)  NOT NULL DEFAULT 0,
                               active              TINYINT(1)     NOT NULL DEFAULT 1,
                               version             BIGINT         NOT NULL DEFAULT 0,
                               created_at          DATETIME(6)    NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
                               updated_at          DATETIME(6)    NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
                               PRIMARY KEY (id),
                               UNIQUE KEY uk_raw_materials_public_id (public_id),
                               UNIQUE KEY uk_raw_materials_code (code),
                               KEY idx_raw_materials_category (category),
                               CONSTRAINT chk_rm_category CHECK (category IN ('FABRIC','BLANK_GARMENT','CONSUMABLE','PACKAGING')),
                               CONSTRAINT chk_rm_on_hand_nonneg  CHECK (on_hand >= 0),
                               CONSTRAINT chk_rm_reserved_nonneg CHECK (reserved >= 0),
                               CONSTRAINT chk_rm_threshold_nonneg CHECK (low_stock_threshold >= 0),
                               CONSTRAINT chk_rm_unit_cost_nonneg CHECK (unit_cost >= 0),
                               CONSTRAINT chk_rm_reserved_le_on_hand CHECK (reserved <= on_hand)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;